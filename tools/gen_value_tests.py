#!/usr/bin/env python3
"""Generate the value-copy regression matrix and its debug-build output fixtures.

Run from any directory after bootstrapping bin/sloppy. --check verifies that the
committed sources and fixtures reproduce exactly; fixtures are never taken from
an optimized build. CI needs only the generated tests, not this script.

Each family crosses five storage origins with ten mutation paths and both
boolean inputs. Each invocation observes local, field, whole-struct, heap-element
and tuple-element copies. Inline/non-inline mutation and return helpers are
explicit, so changes to the inliner's size thresholds cannot remove coverage.
"""

import argparse
from dataclasses import dataclass
import os
from pathlib import Path
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
TYPES = """struct F32s:
    x: f32
    y: f32
struct F64s:
    x: f64
    y: f64
struct Ints:
    x: int
    y: i32
struct Mixed:
    x: f32
    y: f64
    z: int
struct Nested:
    a: F32s
    b: Ints
struct Fixed:
    a: f32[3]
    b: int[2]
"""


@dataclass(frozen=True)
class Kind:
    name: str
    ty: str
    initial: str
    replacement: str
    fields: tuple[str, ...]
    compound: str = ""

    def values(self, base):
        return ", ".join(base + field for field in self.fields)


KINDS = (
    Kind("vec2", "vec2", "vec2(3, 6)", "vec2(9, 12)", (".x", ".y"), " += vec2(2)"),
    Kind("vec3", "vec3", "vec3(3, 6, 9)", "vec3(12, 15, 18)", (".x", ".y", ".z"), " += vec3(2)"),
    Kind("vec4", "vec4", "vec4(3, 6, 9, 12)", "vec4(15, 18, 21, 24)", (".x", ".y", ".z", ".w"), " += vec4(2)"),
    Kind("mat4", "mat4", "mat4(3)", "mat4(9)", tuple(f"[{i}].{c}" for i in range(4) for c in "xyzw")),
    Kind("f32", "F32s", "F32s(3, 6)", "F32s(9, 12)", (".x", ".y")),
    Kind("f64", "F64s", "F64s(3, 6)", "F64s(9, 12)", (".x", ".y")),
    Kind("ints", "Ints", "Ints(3000000001, -6)", "Ints(-9000000001, 12)", (".x", ".y")),
    Kind("mixed", "Mixed", "Mixed(3, 6, 3000000001)", "Mixed(9, 12, -9000000001)", (".x", ".y", ".z")),
    Kind("nested", "Nested", "Nested(F32s(3, 6), Ints(9, -12))", "Nested(F32s(15, 18), Ints(21, -24))", (".a.x", ".a.y", ".b.x", ".b.y")),
    Kind("fixed", "Fixed", "Fixed([f32(3), f32(6), f32(9)], [12, 15])", "Fixed([f32(18), f32(21), f32(24)], [27, 30])", (".a[0]", ".a[1]", ".a[2]", ".b[0]", ".b[1]")),
    Kind("tuple", "(F32s, F64s)", "(F32s(3, 6), F64s(9, 12))", "(F32s(15, 18), F64s(21, 24))", (".0.x", ".0.y", ".1.x", ".1.y")),
    Kind("fixed_structs", "F32s[2]", "[F32s(3, 6), F32s(9, 12)]", "[F32s(15, 18), F32s(21, 24)]", ("[0].x", "[0].y", "[1].x", "[1].y")),
    Kind("array_structs", "F32s[]", "[F32s(3, 6), F32s(9, 12)]", "[F32s(15, 18), F32s(21, 24)]", ("[0].x", "[0].y", "[1].x", "[1].y")),
)

ORIGINS = ("param", "global", "local", "element", "nested")
MODES = ("assign", "compound", "member", "inline_call", "call", "if", "else", "match", "loop", "return")


def program(k):
    out = ["# requires: sloppy", "# Generated by tools/gen_value_tests.py; edit the generator instead.",
           "# mode: " + ", ".join(f"{i}={s}" for i, s in enumerate(MODES)), TYPES.rstrip(),
           f"struct Cell:\n    v: {k.ty}\n    pad = 71", "struct Outer:\n    inner: Cell\n    pad = 83",
           f"g = Cell({k.initial})"]
    for attr, suffix in (("inline", "in"), ("noinline", "out")):
        out += [f"@{attr}", f"change_{suffix} = (v: mut {k.ty}):", f"    v = {k.replacement}",
                f"@{attr}", f"saved_{suffix} = (s: mut Cell) -> {k.ty}:", "    old = s.v",
                f"    s.v{k.fields[0]} *= 2", "    old",
                f"@{attr}", f"argument_{suffix} = (s: mut Cell, old: {k.ty}) -> {k.ty}:",
                f"    s.v{k.fields[0]} *= 2", "    old"]
    for origin in ORIGINS:
        params = {"param": "s: mut Cell, ", "global": "", "local": "",
                  "element": "xs: mut Cell[], i: int, ", "nested": "o: mut Outer, "}[origin]
        root = {"param": "s", "global": "g", "local": "s", "element": "xs[i]", "nested": "o.inner"}[origin]
        v = root + ".v"
        lane = v + k.fields[0]
        out += ["", "@noinline", f"{origin}_case = ({params}mode: int, take: bool):"]
        if origin == "global": out += ["    global g"]
        if origin in ("global", "local"): out += [f"    {root} = Cell({k.initial})"]
        # Keep a copy-only relay: its scalarized lanes have integer register
        # types even when the payload is float. Both snapshots must alias the
        # intervening typed stores (the original M_BITS regression).
        # Allocate containers before these last snapshots: allocator/helper
        # calls between snapshots and mutation would mask memory-CSE failures.
        out += [f"    whole = {root}", f"    field = Cell({k.replacement})",
                f"    elements = [{root}]", "    element = elements[0]",
                f"    pair = ({root}, 97)", "    tuple_element = pair.0",
                f"    relay = {v}", "    first = relay", "    field.v = first", f"    before = {lane}"]
        change = f"{v} = {k.replacement}"
        emit = [f"observed_relay = {v}", "observed = observed_relay",
                f"check = f64(first{k.fields[0]}) + f64({lane}) - f64(observed{k.fields[0]})",
                f'print("{origin}", mode, take, "before", before, "check", check)',
                f'print("local", {k.values("first")})', f'print("whole", {k.values("whole.v")})',
                f'print("field", {k.values("field.v")})', f'print("element", {k.values("element.v")})',
                f'print("tuple", {k.values("tuple_element.v")})',
                f'print("observed", {k.values("observed")})', f'print("original", {k.values(v)})']
        out += ["    match mode:", f"        0: {change}",
                "        1: " + (v + k.compound if k.compound else lane + " += 2"),
                f"        2: {lane} *= 2", f"        3: change_in({v})", f"        4: change_out({v})",
                "        5:", f"            if take: {change}", "        6:",
                "            if take: pass", f"            else: {change}", "        7:",
                "            match take:", f"                true: {change}", "                false: pass",
                "        8:", f"            loop j in 0..(if take: 3 else: 0): {lane} += 1", "        _:",
                "            if take:", f"                {change}"]
        out += ["                " + line for line in emit] + ["                return"]
        out += ["    " + line for line in emit]
        # Two snapshots around another typed store exercise forwarding and the
        # reverse bit-store -> float-load invalidation without a print in between.
        out += [f"    second = {v}", f"    {lane} += 1",
                f'    print("second", {k.values("second")}, "final", {k.values(v)})']
    out += ["", "# Reverse copies and two loop-carried memory-generation checks.", "@noinline",
            "reverse_case = (s: mut Cell, take: bool):", f"    local: {k.ty} = {k.initial}",
            f"    before = s.v{k.fields[0]}", "    s.v = local", f"    after = s.v{k.fields[0]}",
            f"    if take: local = {k.replacement}", "    saved = s.v", "    total = 0.0",
            "    loop i in 0..3:", "        old = s.v", f"        s.v{k.fields[0]} += 1", "        now = s.v",
            f"        total += f64(now{k.fields[0]}) - f64(old{k.fields[0]})",
            f'    print("reverse", take, before, after, total, {k.values("local")}, {k.values("saved")}, {k.values("s.v")})',
            f"    replacement: {k.ty} = {k.replacement}", "    sum = 0.0", "    loop i in 0..3:",
            f"        sum += f64(s.v{k.fields[0]})", "        s.v = replacement",
            f'    print("bit stores", sum, {k.values("replacement")}, {k.values("s.v")})',
            "", "# Runtime parameters keep both control-flow paths in the non-inlined cases.",
            "loop mode in 0..10:", "    loop take in [false, true]:", f"        s = Cell({k.initial})",
            "        param_case(s, mode, take)", "        global_case(mode, take)", "        local_case(mode, take)",
            f"        xs = [Cell({k.replacement}), Cell({k.initial})]", "        element_case(xs, 1, mode, take)",
            f"        o = Outer(Cell({k.initial}))", "        nested_case(o, mode, take)",
            "# Aggregate return snapshots and an argument aliased by a mut argument."]
    out += ["loop take in [false, true]:", f"    rev = Cell({k.replacement})", "    reverse_case(rev, take)"]
    for suffix in ("in", "out"):
        out += [f"s_{suffix} = Cell({k.initial})", f"r_{suffix} = saved_{suffix}(s_{suffix})",
                f'print("return {suffix}", {k.values("r_" + suffix)}, {k.values("s_" + suffix + ".v")})',
                f"a_{suffix} = argument_{suffix}(s_{suffix}, s_{suffix}.v)",
                f'print("argument {suffix}", {k.values("a_" + suffix)}, {k.values("s_" + suffix + ".v")})']
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--compiler", type=Path, default=ROOT / "bin/sloppy")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    scratch = Path.home() / "dev/tmp/value-tests/tmp"
    scratch.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ, TMPDIR=str(scratch), SLOPPY_LIB=str(ROOT / "lib"), SLOPPY_EMIT_WORKERS="1")
    env.pop("DISPLAY", None)
    env.pop("WAYLAND_DISPLAY", None)
    with tempfile.TemporaryDirectory(prefix="generate-", dir=scratch) as tmp:
        for k in KINDS:
            source = program(k)
            path = ROOT / "tests/t" / f"value_copy_{k.name}.jo"
            if args.check:
                if path.read_text() != source: raise SystemExit(f"stale generated source: {path}")
            else:
                path.write_text(source)
            exe = Path(tmp) / k.name
            subprocess.run([str(args.compiler.resolve()), "build", str(path), "-o", str(exe)],
                           env=env, check=True, timeout=60)
            result = subprocess.run([str(exe)], env=env, capture_output=True, check=True, timeout=20)
            if result.stderr: raise SystemExit(result.stderr.decode())
            fixture = path.with_suffix(".out")
            if args.check:
                if fixture.read_bytes() != result.stdout: raise SystemExit(f"stale debug output: {fixture}")
            else:
                fixture.write_bytes(result.stdout)
            print(f"{path.name}: 100 storage/mutation cases, 4 argument/return cases, 2 reverse/loop cases")
    print(f"{len(KINDS)} families, {len(KINDS) * 106} cases; {'verified' if args.check else 'generated'}")


if __name__ == "__main__":
    main()
